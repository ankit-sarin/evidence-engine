"""12n-U12-C2A A3 — renders lock_census.json as lock_census_table.md. usage, from the repository
root: census_table.py <lock_census.json> <plan.md> > lock_census_table.md
The ledger column is a text search of the plan's "### Retention ledger (R31)" section for the path."""
import json, re, sys
d = json.load(open(sys.argv[1])); plan = open(sys.argv[2], encoding="utf-8").read()
led = plan[plan.index("### Retention ledger (R31)"):]; led = led[:led.index("\n### ", 10)]
def yn(r, c):
    x = r[c]
    if x["unlocked"] and x["locked"]: return "both" + (" (unlocked: opt-out branch only)" if x["unlocked_only_via_optout"] else "")
    if x["unlocked"]: return "UNLOCKED"
    if x["locked"]: return "locked"
    return "."
def short(ch): return (ch or "").replace("engine.", "e.").replace("analysis.", "a.").replace("scripts.", "s.")
print("# Lock census — every entry point under engine/, scripts/, analysis/ (12n-U12-C2A, A3)\n")
print(f"Generated by `census_table.py` from `lock_census.json` (`lock_census.py`, AST only). {d['python_entry_points']} Python entry points; shell scripts: {', '.join('`'+s+'`' for s in d['shell_scripts'])}.\n")
print("`UNLOCKED` = a resolved static path outside any `with hold_experiment_lock(...)`; `locked` = every resolved path is inside one; `both` = some of each; `.` = no resolved path. `[L]` in a chain marks a step inside the lock; `~` marks a method-name over-approximation.\n")
print("## Counts by tree and category\n\n| tree | category | entry points |\n| --- | --- | --- |")
for t, cs in sorted(d["counts_by_tree_and_category"].items()):
    for c, n in sorted(cs.items()): print(f"| {t} | {c} | {n} |")
print("\n## Entry points with a path to a local model call, a restart, a cloud call, or the lock\n")
print("| entry | category | local call | proactive restart | last-resort restart | preflight probe | cloud | lock taken in | frozen marker in the file | retention ledger |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
rest = []
for r in d["rows"]:
    if r["category"] == "none" and not r["lock_sites_reached"]: rest.append(r); continue
    print(f"| `{r['entry']}` | {r['category']} | {yn(r,'local_call')} | {yn(r,'restart_proactive')} | {yn(r,'restart_last_resort')} | {yn(r,'preflight_probe')} | {yn(r,'cloud_call')} | {', '.join('`'+s+'`' for s in r['lock_sites_reached']) or '—'} | {'yes' if r['frozen_marker'] else '—'} | {'named' if r['entry'] in led else '—'} |")
print("\n## Call chains (shortest resolved)\n")
for r in d["rows"]:
    if r["category"] == "none" and not r["lock_sites_reached"]: continue
    print(f"**`{r['entry']}`**\n")
    for c in ("local_call", "restart_proactive", "preflight_probe", "cloud_call", "ollama_read"):
        for side in ("unlocked", "locked"):
            if r[c][side]: print(f"- {c}, {side}{' (opt-out branch only)' if side == 'unlocked' and r[c]['unlocked_only_via_optout'] else ''}: `{short(r[c][side])}`")
    if r["process_sites_reached"]: print("- process sites reached: " + "; ".join(f"`{s}`" for s in r["process_sites_reached"]))
    print()
print("## `scripts/run_pipeline.py`, by stage function\n")
for fn, r in d["stages"].items():
    print(f"**`{fn}`** — lock taken in: {', '.join(r['lock_sites_reached']) or 'nowhere'}\n")
    for c in ("local_call", "restart_proactive", "preflight_probe", "ollama_read"):
        for side in ("unlocked", "locked"):
            if r[c][side]: print(f"- {c}, {side}{' (opt-out branch only)' if side == 'unlocked' and r[c]['unlocked_only_via_optout'] else ''}: `{short(r[c][side])}`")
    print()
print(f"## Entry points with no resolved path ({len(rest)})\n")
print("| entry | process sites reached | frozen marker | retention ledger |\n| --- | --- | --- | --- |")
for r in rest: print(f"| `{r['entry']}` | {'; '.join('`'+s+'`' for s in r['process_sites_reached']) or '—'} | {'yes' if r['frozen_marker'] else '—'} | {'named' if r['entry'] in led else '—'} |")
